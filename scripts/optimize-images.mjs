/**
 * Image pipeline.
 *
 * Drop originals into `assets/source/` and run `npm run images`:
 *
 *   assets/source/profile/<name>.(png|jpg|webp)        → public/images/profile/<name>.webp (≤1200px square)
 *                                                        + public/images/profile/<name>-480.jpg (for Open Graph / JSON-LD)
 *   assets/source/projects/<project-id>/<name>.(png|…) → public/images/projects/<project-id>/<name>.webp (≤1600px wide)
 *
 * It also writes `src/content/images.generated.ts` with width, height and a
 * tiny blur placeholder for every output, so `next/image` never shifts layout.
 * Re-encoding everything takes a few seconds, so there is no cache.
 */
import { mkdir, readdir, rm, writeFile } from "node:fs/promises";
import { basename, extname, join, relative, sep } from "node:path";
import sharp from "sharp";

const ROOT = process.cwd();
const SOURCE = join(ROOT, "assets", "source");
const OUT = join(ROOT, "public", "images");
const GENERATED = join(ROOT, "src", "content", "images.generated.ts");
const EXT = /\.(png|jpe?g|webp|avif)$/i;

async function* walk(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) yield* walk(full);
    else if (EXT.test(entry.name)) yield full;
  }
}

function publicPath(absolute) {
  return "/" + relative(join(ROOT, "public"), absolute).split(sep).join("/");
}

async function blurPlaceholder(pipeline) {
  const buf = await pipeline.clone().resize(12, 12, { fit: "inside" }).webp({ quality: 40 }).toBuffer();
  return `data:image/webp;base64,${buf.toString("base64")}`;
}

const meta = {};
let written = 0;

await mkdir(OUT, { recursive: true });

for await (const file of await walk(SOURCE)) {
  const rel = relative(SOURCE, file).split(sep);
  const [kind] = rel;
  const name = basename(file, extname(file)).toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

  if (kind === "profile") {
    const dir = join(OUT, "profile");
    await mkdir(dir, { recursive: true });
    const webp = join(dir, `${name}.webp`);
    const jpg = join(dir, `${name}-480.jpg`);
    const base = sharp(file).rotate();
    await base.clone().resize(1200, 1200, { fit: "cover", position: "attention" }).webp({ quality: 84 }).toFile(webp);
    await base.clone().resize(480, 480, { fit: "cover", position: "attention" }).jpeg({ quality: 86, mozjpeg: true }).toFile(jpg);
    written++;
    const out = sharp(webp);
    const { width, height } = await out.metadata();
    meta[publicPath(webp)] = { width, height, blurDataURL: await blurPlaceholder(out) };
    continue;
  }

  if (kind === "projects" && rel.length === 3) {
    const [, project] = rel;
    const dir = join(OUT, "projects", project);
    await mkdir(dir, { recursive: true });
    const webp = join(dir, `${name}.webp`);
    await sharp(file)
      .rotate()
      .resize({ width: 1600, withoutEnlargement: true })
      .webp({ quality: 82, effort: 5 })
      .toFile(webp);
    written++;
    const out = sharp(webp);
    const { width, height } = await out.metadata();
    meta[publicPath(webp)] = { width, height, blurDataURL: await blurPlaceholder(out) };
    continue;
  }

  console.warn(`skipped ${relative(ROOT, file)} (expected assets/source/profile/* or assets/source/projects/<id>/*)`);
}

// Remove outputs whose source has gone away (the -480.jpg companions are kept alongside their .webp).
for await (const file of await walk(OUT)) {
  const key = publicPath(file);
  if (!meta[key] && !meta[key.replace(/-480\.jpg$/, ".webp")]) {
    await rm(file);
    console.log(`removed stale ${relative(ROOT, file)}`);
  }
}

const sorted = Object.fromEntries(Object.entries(meta).sort(([a], [b]) => a.localeCompare(b)));
const banner = `/* Generated by scripts/optimize-images.mjs. Do not edit; run \`npm run images\`. */\n`;
const body = `export interface ImageMeta {\n  width: number;\n  height: number;\n  blurDataURL: string;\n}\n\nexport const imageMeta: Record<string, ImageMeta> = ${JSON.stringify(sorted, null, 2)};\n`;
await writeFile(GENERATED, banner + body);

console.log(`${Object.keys(sorted).length} images indexed, ${written} encoded → ${relative(ROOT, GENERATED)}`);
